CREATE TABLE public.publicacoes_escala (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 area_id INTEGER NOT NULL REFERENCES public.areas(id),publicado_por INTEGER REFERENCES public.usuarios(id),
 inicio TEXT NOT NULL,fim TEXT NOT NULL,quantidade INTEGER NOT NULL,
 criado_em TEXT NOT NULL DEFAULT to_char(timezone('America/Sao_Paulo',now()),'YYYY-MM-DD HH24:MI:SS'),
 notificado_em TEXT,notificado_por INTEGER REFERENCES public.usuarios(id),destinatarios INTEGER NOT NULL DEFAULT 0,
 CHECK(fim>=inicio),CHECK(quantidade>0)
);
ALTER TABLE public.escalas ADD COLUMN publicacao_id INTEGER REFERENCES public.publicacoes_escala(id) ON DELETE SET NULL;
CREATE INDEX escalas_publicacao ON public.escalas(publicacao_id);
CREATE INDEX publicacoes_area ON public.publicacoes_escala(area_id,id);
CREATE TABLE public.notificacoes (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
 publicacao_id INTEGER NOT NULL REFERENCES public.publicacoes_escala(id) ON DELETE CASCADE,
 titulo TEXT NOT NULL,mensagem TEXT NOT NULL,link TEXT NOT NULL,
 criado_em TEXT NOT NULL DEFAULT to_char(timezone('America/Sao_Paulo',now()),'YYYY-MM-DD HH24:MI:SS'),lida_em TEXT,
 UNIQUE(publicacao_id,usuario_id)
);
CREATE INDEX notificacoes_usuario ON public.notificacoes(usuario_id,lida_em,id);
ALTER TABLE public.publicacoes_escala ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notificacoes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.publicacoes_escala,public.notificacoes FROM anon,authenticated;
REVOKE ALL ON SEQUENCE public.publicacoes_escala_id_seq,public.notificacoes_id_seq FROM anon,authenticated;
INSERT INTO public.publicacoes_escala(area_id,publicado_por,inicio,fim,quantidade,criado_em)
 SELECT g.area_id,COALESCE(e.autorizado_por,e.indicado_por),MIN(c.data),MAX(c.data),COUNT(*),MAX(e.criado_em)
 FROM public.escalas e JOIN public.cultos c ON c.id=e.culto_id JOIN public.congregacoes g ON g.id=c.congregacao_id
 WHERE e.autorizacao='autorizada' AND c.cancelado=0
 GROUP BY g.area_id,COALESCE(e.autorizado_por,e.indicado_por);
UPDATE public.escalas SET publicacao_id=(SELECT p.id FROM public.publicacoes_escala p JOIN public.cultos c ON c.id=escalas.culto_id JOIN public.congregacoes g ON g.id=c.congregacao_id
 WHERE c.cancelado=0 AND p.area_id=g.area_id AND (p.publicado_por=COALESCE(escalas.autorizado_por,escalas.indicado_por) OR (p.publicado_por IS NULL AND COALESCE(escalas.autorizado_por,escalas.indicado_por) IS NULL)) LIMIT 1)
 WHERE autorizacao='autorizada';
