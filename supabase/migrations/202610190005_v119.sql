CREATE OR REPLACE FUNCTION public.validar_area_usuario() RETURNS trigger LANGUAGE plpgsql SET search_path=public AS $$
BEGIN
 IF NEW.congregacao_id IS NOT NULL AND NEW.area_id IS NOT NULL AND NOT EXISTS(SELECT 1 FROM public.congregacoes WHERE id=NEW.congregacao_id AND area_id=NEW.area_id) THEN
  RAISE EXCEPTION 'Congregação fora da área';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER usuario_area BEFORE INSERT OR UPDATE OF congregacao_id,area_id ON public.usuarios FOR EACH ROW EXECUTE FUNCTION public.validar_area_usuario();
REVOKE ALL ON FUNCTION public.validar_area_usuario() FROM PUBLIC;
